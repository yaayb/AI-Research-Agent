"""Standalone, print-styled HTML report (single file, inline CSS, no external assets).

Design decision: convert the canonical Markdown with python-markdown (tables extension) and wrap it
in a self-contained template with ``@media print`` rules, so the file can be emailed or printed.
"""
from __future__ import annotations

import html
import re
from typing import Any

import markdown as md

from app.exporters.markdown_exporter import render_markdown

CSS = """
:root{--ink:#1b2430;--muted:#5b6675;--accent:#3b4cca;--line:#e3e7ee;--bg:#fff}
*{box-sizing:border-box}body{font:16px/1.65 Georgia,'Times New Roman',serif;color:var(--ink);background:#f4f6fa;margin:0}
main{max-width:900px;margin:32px auto;background:var(--bg);padding:48px 56px;border-radius:10px;box-shadow:0 2px 18px rgba(20,30,60,.08)}
h1{font:700 2rem/1.2 'Segoe UI',Helvetica,Arial,sans-serif;margin:0 0 .6em;color:var(--accent)}
h2{font:600 1.35rem 'Segoe UI',Helvetica,Arial,sans-serif;margin-top:2em;padding-bottom:.25em;border-bottom:2px solid var(--accent)}
h3{font:600 1.05rem 'Segoe UI',Helvetica,Arial,sans-serif;margin-top:1.4em;color:#2a3550}
a{color:var(--accent);text-decoration:none;word-break:break-word}a:hover{text-decoration:underline}
blockquote{margin:1em 0;padding:.8em 1.2em;background:#eef1fb;border-left:4px solid var(--accent);color:var(--muted);border-radius:4px}
table{border-collapse:collapse;width:100%;margin:1em 0;font:14px/1.45 'Segoe UI',Helvetica,Arial,sans-serif}
th{background:var(--accent);color:#fff;text-align:left}th,td{padding:8px 10px;border:1px solid var(--line);vertical-align:top}
tr:nth-child(even) td{background:#f8f9fc}code{background:#f0f2f7;padding:1px 5px;border-radius:3px}
footer{margin-top:3em;font:12px 'Segoe UI',sans-serif;color:var(--muted);text-align:center}
@media print{body{background:#fff}main{box-shadow:none;margin:0;padding:0;max-width:none}a{color:var(--accent)}h2{break-after:avoid}table,tr{break-inside:avoid}}
"""


def render_html(report: dict[str, Any]) -> str:
    body = md.markdown(render_markdown(report), extensions=["tables", "sane_lists", "fenced_code"])
    body = re.sub(r'<a href="(https?://[^"]+)"', r'<a href="\1" target="_blank" rel="noopener noreferrer"', body)
    title = html.escape(report["title"])
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>{title}</title><style>{CSS}</style></head><body><main>{body}"
            f"<footer>Generated by DeepBrief AI · {html.escape(report.get('generated_at', ''))}</footer></main></body></html>")
